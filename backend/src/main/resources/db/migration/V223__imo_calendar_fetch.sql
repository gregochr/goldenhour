-- V223: the IMO meteor-calendar refresh (meteor-showers-plan Phase 4).
--
-- imo_calendar_fetch is the job's own log: one row per calendar year per run, so the alert rules (INVALID once per
-- distinct PDF, FAILED on exactly the third in a row) read the database and nothing lives in memory, as tide_fetch
-- does for tides. outcome is STORED | UNCHANGED | NOT_PUBLISHED | FAILED | INVALID. sha256 is the SHA-256 of the
-- PDF fetched, when there was one. detail is a short, truncated account (the failing shower, the HTTP error).
CREATE TABLE imo_calendar_fetch (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_year INTEGER                  NOT NULL,
    attempted_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    outcome       VARCHAR(16)              NOT NULL,
    http_status   INTEGER,
    sha256        VARCHAR(64),
    detail        VARCHAR(500),
    CONSTRAINT ck_imo_calendar_fetch_outcome
        CHECK (outcome IN ('STORED', 'UNCHANGED', 'NOT_PUBLISHED', 'FAILED', 'INVALID'))
);

CREATE INDEX idx_imo_calendar_fetch_year_attempted
    ON imo_calendar_fetch (calendar_year, attempted_at DESC, id DESC);


-- V208: weekly gauge check of WorldTides predictions (tide-source-integrity-plan P4).
--
-- One row per Environment Agency gauge per check run: the median timing and height error of the
-- last 7 days' predicted high waters against that gauge's measured water. The readings themselves are
-- never stored (Open Government Licence v3.0); only these aggregates are.
CREATE TABLE tide_gauge_check (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gauge_measure_id         VARCHAR(128)     NOT NULL,
    location_id              BIGINT           NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
    run_at                   TIMESTAMP        NOT NULL,
    window_from              TIMESTAMP        NOT NULL,
    window_to                TIMESTAMP        NOT NULL,
    paired_highs             INTEGER          NOT NULL,
    median_timing_error_min  DOUBLE PRECISION NOT NULL,
    median_height_error_m    DOUBLE PRECISION NOT NULL,
    flagged                  BOOLEAN          NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_tide_gauge_check_location_run ON tide_gauge_check (location_id, run_at DESC);

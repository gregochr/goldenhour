-- V224: Met Office weather warnings (weather-warnings-plan W1a).
--
-- weather_warning_version is INSERT-ONLY: one row per (warning_id, warning_version), never updated, never deleted.
-- The unique key makes ingest idempotent (re-polling a stored version is a no-op). "Active at T" is derived at read
-- time from received_at, status and valid_to, so a cancellation is a new row, never an edit of an old one.
--   status            ACTIVE | CANCELLED, normalised by the feed parser; source_status keeps the feed's own word.
--   warning_level     the Met Office level word (Yellow, Amber, Red ...) as a string, never a closed enum.
--   weather_types     JSON array text of the feed's weather types, kept as received (unknown types are kept).
--   what_to_expect, affected_areas   JSON array text.
--   geometry          the feed's GeoJSON MultiPolygon as text; simplified_geometry is the thinned map copy.
--   simulated         true for an admin-inserted test warning; such rows never reach a shared payload.
--   received_at       the poller's own clock when it stored the row (what "we had received" means under Rewind).
CREATE TABLE weather_warning_version (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warning_id          VARCHAR(100)             NOT NULL,
    warning_version     INTEGER                  NOT NULL,
    status              VARCHAR(16)              NOT NULL,
    source_status       VARCHAR(50),
    warning_level       VARCHAR(30),
    weather_types       TEXT,
    likelihood          VARCHAR(50),
    impact              VARCHAR(50),
    valid_from          TIMESTAMP WITH TIME ZONE,
    valid_to            TIMESTAMP WITH TIME ZONE,
    issued_at           TIMESTAMP WITH TIME ZONE,
    modified_at         TIMESTAMP WITH TIME ZONE,
    headline            TEXT,
    what_to_expect      TEXT,
    further_details     TEXT,
    affected_areas      TEXT,
    source_url          VARCHAR(500),
    geometry            TEXT,
    simplified_geometry TEXT,
    simulated           BOOLEAN                  NOT NULL DEFAULT FALSE,
    received_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_weather_warning_version UNIQUE (warning_id, warning_version),
    CONSTRAINT ck_weather_warning_version_status CHECK (status IN ('ACTIVE', 'CANCELLED'))
);

CREATE INDEX idx_weather_warning_version_id_version
    ON weather_warning_version (warning_id, warning_version DESC);

CREATE INDEX idx_weather_warning_version_valid_to
    ON weather_warning_version (valid_to);


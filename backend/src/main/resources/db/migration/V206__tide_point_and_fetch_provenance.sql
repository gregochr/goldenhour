-- V206: tide point and WorldTides fetch provenance (tide-source-integrity-plan P1a).
--
-- tide_lat / tide_lng: an optional point sent to WorldTides in place of the pin, for locations whose own
-- sea area is served by an unreliable model cell. Both set or both NULL. Nothing but WorldTides reads it.
ALTER TABLE locations ADD COLUMN tide_lat DOUBLE PRECISION;
ALTER TABLE locations ADD COLUMN tide_lng DOUBLE PRECISION;
ALTER TABLE locations ADD CONSTRAINT chk_locations_tide_point_pair
    CHECK ((tide_lat IS NULL) = (tide_lng IS NULL));

-- tide_fetch: one row per WorldTides call, recording where its data came from. reason is a plain string
-- code (SEED, RESEED, TAIL, POINT_CHANGE, BACKFILL), not an enum column.
CREATE TABLE tide_fetch (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id      BIGINT           NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
    fetched_at       TIMESTAMP        NOT NULL,
    window_from      TIMESTAMP,
    window_to        TIMESTAMP,
    reason           VARCHAR(16)      NOT NULL,
    success          BOOLEAN          NOT NULL,
    request_lat      DOUBLE PRECISION,
    request_lng      DOUBLE PRECISION,
    response_lat     DOUBLE PRECISION,
    response_lng     DOUBLE PRECISION,
    atlas            VARCHAR(64),
    station          VARCHAR(64),
    response_datum   VARCHAR(64),
    call_count       INTEGER,
    extremes_stored  INTEGER          NOT NULL DEFAULT 0
);

CREATE INDEX idx_tide_fetch_location_fetched ON tide_fetch (location_id, fetched_at DESC);

-- Ten locations read tide times from a neighbouring point: WorldTides' FES2022 cell at their own pin gives
-- times 35-55 minutes late from 6 Dec 2026. Each tide point is a snapshot of the source location's own
-- coordinates, matched by exact name. A name that matches nothing updates nothing and never fails the
-- deploy; the NOTICE reports how many rows were set (10 in production, 0 on an empty roster).
DO $$
DECLARE
    updated INTEGER := 0;
    batch   INTEGER;
    pair    RECORD;
BEGIN
    FOR pair IN
        SELECT * FROM (VALUES
            ('Staithes', 'Runswick Bay'),
            ('Saltburn-by-the-Sea', 'Redcar'),
            ('Black Hole', 'Alnmouth'),
            ('Cullernose Point', 'Alnmouth'),
            ('Dunstanburgh Castle', 'Alnmouth'),
            ('Howick Scar', 'Alnmouth'),
            ('Rumbling Kern', 'Alnmouth'),
            ('Sugar Sands', 'Alnmouth'),
            ('The Bathing House, Craster', 'Alnmouth'),
            ('Cresswell Beach', 'Newbiggin-by-the-Sea')
        ) AS v(target_name, source_name)
    LOOP
        UPDATE locations t
        SET tide_lat = s.lat, tide_lng = s.lon
        FROM locations s
        WHERE t.name = pair.target_name AND s.name = pair.source_name;
        GET DIAGNOSTICS batch = ROW_COUNT;
        updated := updated + batch;
    END LOOP;
    RAISE NOTICE 'V206: set % tide point(s)', updated;
END $$;

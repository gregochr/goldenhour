-- V188: big seas B1 (big-seas-plan) -- sample the sea at every daylight high water.
--
-- 1. locations gains three nullable columns that mark a location as a wave-watching structure (a
--    pier, breakwater or lighthouse that the sea can break over): coastal_structure, the compass
--    bearing the structure faces (structure_faces_deg, 0-359) and the chip's short name
--    (structure_label). Seven structures are seeded below, BY NAME (never by id: the V60 mistake).
--    The names were confirmed against production on 2026-10-22. Ordinary updatable columns,
--    migration-written only; there is no admin UI for them in this series.
--
-- 2. marine_high_water stores the sea state at EVERY daylight high water of a structure location,
--    qualifying or not, so the thresholds can be tuned over the winter from real numbers. Whether a
--    high water is "big seas" is decided at serve time from these stored numbers, never persisted.
--    One row per (location_id, hw_time): the peak wave_height inside the high water's +-90 minute
--    window (clipped to civil dawn..dusk), with the period and swell values at that peak hour.
--    The refresh deletes a location's rows over the date range and re-inserts them in one
--    transaction, because high-water times move when tides are re-fetched. All times are UTC with
--    no zone, as tide_extreme.event_time is.
--
-- 3. Correction to V123 (which is NOT edited: applied migrations are history). V123's comments say
--    marine_wave is "sampled at the aligned high-water time". It never was: the briefing marine
--    refresh samples it at SUNRISE and SUNSET (grain: location, date, event). marine_wave keeps that
--    event grain; the high-water grain lives in the new marine_high_water table.

ALTER TABLE locations ADD COLUMN coastal_structure VARCHAR(20);
ALTER TABLE locations ADD COLUMN structure_faces_deg INTEGER;
ALTER TABLE locations ADD COLUMN structure_label VARCHAR(40);

ALTER TABLE locations ADD CONSTRAINT ck_locations_structure_faces_deg
    CHECK (structure_faces_deg IS NULL OR (structure_faces_deg >= 0 AND structure_faces_deg <= 359));

UPDATE locations SET coastal_structure = 'PIER', structure_faces_deg = 45,
       structure_label = 'Roker Pier' WHERE name = 'Roker Pier & Lighthouse';
UPDATE locations SET coastal_structure = 'LIGHTHOUSE', structure_faces_deg = 90,
       structure_label = 'St Mary''s' WHERE name = 'St. Mary''s Lighthouse';
UPDATE locations SET coastal_structure = 'PIER', structure_faces_deg = 45,
       structure_label = 'Amble piers' WHERE name = 'Amble';
UPDATE locations SET coastal_structure = 'PIER', structure_faces_deg = 0,
       structure_label = 'Saltburn Pier' WHERE name = 'Saltburn-by-the-Sea';
UPDATE locations SET coastal_structure = 'PIER', structure_faces_deg = 0,
       structure_label = 'Whitby piers' WHERE name = 'Whitby Piers';
UPDATE locations SET coastal_structure = 'PIER', structure_faces_deg = 90,
       structure_label = 'Seaham Pier' WHERE name = 'Seaham North Pier & Lighthouse';
UPDATE locations SET coastal_structure = 'BREAKWATER', structure_faces_deg = 90,
       structure_label = 'Hartlepool' WHERE name = 'Hartlepool Headland';

CREATE TABLE marine_high_water (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id          BIGINT         NOT NULL,
    hw_time              TIMESTAMP      NOT NULL,
    hw_height_m          DECIMAL(6, 3),
    window_start         TIMESTAMP      NOT NULL,
    window_end           TIMESTAMP      NOT NULL,
    peak_time            TIMESTAMP      NOT NULL,
    wave_height_m        DOUBLE PRECISION,
    wave_period_s        DOUBLE PRECISION,
    swell_wave_height_m  DOUBLE PRECISION,
    swell_wave_period_s  DOUBLE PRECISION,
    wave_direction_deg   INTEGER,
    evaluated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_marine_high_water_location FOREIGN KEY (location_id)
        REFERENCES locations (id),
    CONSTRAINT uq_marine_high_water UNIQUE (location_id, hw_time)
);

CREATE INDEX idx_marine_high_water_hw_time ON marine_high_water (hw_time);

-- Post-flight: exactly the seven structures must now be marked. A WARNING, not an EXCEPTION: an
-- exception here would block a production restart over a cosmetic miss (a renamed location simply
-- gets no big-seas chip until the owner re-marks it).
DO $$
DECLARE seeded INT;
BEGIN
    SELECT COUNT(*) INTO seeded FROM locations WHERE coastal_structure IS NOT NULL;
    IF seeded <> 7 THEN
        RAISE WARNING 'V188: expected 7 coastal structures seeded, found %', seeded;
    END IF;
END $$;
